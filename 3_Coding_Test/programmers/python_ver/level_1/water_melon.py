# 문제: 프로그래머스 Lv.1 '수박수박수박수박수박수'
# 설명: 길이가 n이고, "수박수박수박수...."와 같은 패턴을 유지하는 문자열을 리턴하는 함수, solution을 완성하세요.
#       예를들어 n이 4이면 "수박수박"을 리턴하고 3이라면 "수박수"를 리턴하면 됩니다.
# 링크: https://school.programmers.co.kr/learn/courses/30/lessons/12922

# 풀이:
# 1. 반복해서 사용할 기본 세트 단어("수박")를 준비한다.
# 2. 목표 길이(n)에 "수박"(2글자) 세트가 몇 번 온전히 들어가는지 몫(n // 2)을 구한다.
# 3. 만약 n이 짝수라면, 딱 맞아떨어지므로 구한 몫만큼 "수박"을 곱해(반복해) 돌려준다.
#    (예: n이 4면 '수박' 2세트 -> "수박수박")
# 4. 만약 n이 홀수라면, 몫만큼 "수박"을 곱한 뒤 마지막에 "수" 한 글자를 덧붙여 돌려준다.
#    (예: n이 3이면 '수박' 1세트 + '수' -> "수박수")

def solution(n):
    
    water_melon = "수박"
    half_len = n // 2
    
    if (n % 2) == 0:
        return water_melon * (half_len)
    else:
        return water_melon * (half_len) + "수"