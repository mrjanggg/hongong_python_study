# 문제: 프로그래머스 Lv.1 '콜라 문제'
# 설명: 빈 병 a개를 주면 콜라 b병을 주는 마트에서, 초기 빈 병 n개로 총 교환받을 수 있는 콜라의 병 수를 계산합니다.
# 링크: https://school.programmers.co.kr/learn/courses/30/lessons/132267

# 풀이:
# 1. 상빈이가 추가로 받아 마신 총 콜라의 병 수를 누적하기 위해 answer를 0으로 초기화합니다.
# 2. 보유한 빈 병 수(n)가 마트의 교환 기준(a) 이상인 동안 while 반복문을 수행합니다.
# 3. 이번 턴에 마트에 빈 병을 주고 새로 받아온 콜라 병 수(taken)를 계산합니다.
#    - n개를 a로 나눈 몫에 b를 곱합니다: taken = (n // a) * b
# 4. 새로 받아온 콜라 병 수를 총 누적 개수(answer)에 더합니다.
# 5. 다음 교환을 위해 상빈이가 쥐고 있는 총 빈 병 수(n)를 즉시 갱신합니다.
#    - [새로 받아 모두 마신 빈 병(taken)] + [이번에 교환하지 못하고 남은 자투리 빈 병(n % a)]
# 6. 더 이상 교환할 수 없어(n < a) 반복문이 종료되면, 누적된 총 콜라 병 수(answer)를 반환합니다.

def solution(a, b, n):
    answer = 0
    
    # 빈 병이 a개 이상 남아있으면 계속 마트에 간다
    while n >= a:
        # 1. 이번에 새로 교환받은 콜라 병 수
        taken = (n // a) * b
        
        # 2. 총 받은 콜라 누적
        answer += taken
        
        # 3. 다음 턴에 내가 쥐고 있는 총 빈 병 수
        #    = (새로 받아 마신 병) + (이번에 미처 못 바꾼 자투리 병)
        n = taken + (n % a)
        
    return answer